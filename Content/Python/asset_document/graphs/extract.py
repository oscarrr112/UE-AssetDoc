"""Live snapshot -> GraphDoc extraction.

Node ids are reused from a previously saved sidecar document (matched by
NodeGuid), then from the Id the node was last applied with (an adapter that
``keeps_authored_ids``: graph.finalize.v1 records it with the node), so that
AI-authored names survive round trips; otherwise ids are deterministic semantic
ids from the schema adapter (``BeginPlay``, ``Branch``, ``Get_Health``,
``Entry``) with ``_2`` suffixes on collision.  Actions are written as the
document applied them when that key still names the node (``K2:Min``), else in
their AI-friendly alias form (``K2:Branch``) when one exists;
signature defaults and flags are written only when they differ from what the
editor would produce on its own.  Extraction is pure and
reconcile(extract(live), live) is an empty plan.
"""
from __future__ import annotations

from typing import Mapping

from asset_document.diagnostics import AssetDocumentContractError
from asset_document.graphs.actions import actions_equal
from asset_document.graphs.live import LiveAsset, LiveGraph, LiveNode
from asset_document.graphs.model import (
    Endpoint, GraphDoc, LinkDoc, NodeDoc, NodeProperties, PinOverride, Signature, Size, UserPin, thaw_json,
)
from asset_document.graphs.reconcile import is_authored_default, is_type_zero, type_zero
from asset_document.graphs.schemas import GENERIC_ADAPTER, SchemaAdapter


def _unique(base: str, used: set[str]) -> str:
    candidate, suffix = base, 2
    while candidate in used:
        candidate, suffix = f"{base}_{suffix}", suffix + 1
    used.add(candidate)
    return candidate


def _hint_graph(graph: LiveGraph, hints: tuple[GraphDoc, ...], name: str | None = None) -> GraphDoc | None:
    name = graph.name if name is None else name
    return next((doc for doc in hints if doc.guid == graph.guid), None) or next(
        (doc for doc in hints if doc.role == graph.role and doc.name.casefold() == name.casefold()), None)


def _assign_ids(nodes: list[LiveNode], hint: GraphDoc | None, adapter: SchemaAdapter) -> dict[str, str]:
    by_guid = {node.guid: node.id for node in (hint.nodes if hint else ()) if node.guid}
    used: set[str] = set()
    ids: dict[str, str] = {}
    for node in nodes:
        hinted = by_guid.get(node.guid)
        if hinted is not None and hinted not in used:
            ids[node.guid] = hinted
            used.add(hinted)
    if adapter.keeps_authored_ids:
        # The Id each node was last applied with (a copy pasted node has none; a clash keeps the first).
        for node in nodes:
            if node.guid not in ids and node.doc_id and node.doc_id not in used:
                ids[node.guid] = node.doc_id
                used.add(node.doc_id)
    # Nodes the adapter ranks first claim their base id before the rest, whatever their place in the graph:
    # a Create may place them earlier than the author did (a called custom event before a comment titled
    # like it), and ids must not follow that order.
    for node in sorted(nodes, key=adapter.id_rank):
        if node.guid not in ids:
            ids[node.guid] = _unique(adapter.node_base_id(node), used)
    return ids


def _overrides(node: LiveNode, adapter: SchemaAdapter, include_defaults: bool = False) -> tuple[PinOverride, ...]:
    """Pin values the node reports: those that differ from the pin's own default; with
    ``include_defaults`` (Verify / Diff, extract's include_defaults) also those equal to it, so an
    authored PinOverride that restates a default compares as present (sparse over defaults)."""
    output = []
    terminator = node.implicit_role == "result"
    for pin in node.pins:
        if (include_defaults and not pin.default_value and not pin.default_object and not pin.default_text
                and pin.is_autogenerated_default and pin.type.category in ("real", "float", "double")
                and pin.type.container == "none" and pin.direction == "input" and not pin.hidden
                and not pin.orphaned and not pin.linked_to):
            # An empty real pin that matches its autogenerated default reads as 0.0 (UEdGraphSchema_K2
            # compares the numbers): a promotable operator's reconstructed pin keeps no text for it.
            output.append(PinOverride(pin.name, value="0.0"))
            continue
        if (not is_authored_default(pin, adapter, terminator=terminator)
                and not (include_defaults and is_authored_default(pin, adapter, defaults=True, terminator=terminator))):
            continue
        if pin.default_object:
            output.append(PinOverride(pin.name, object=pin.default_object))
        elif pin.default_text:
            output.append(PinOverride(pin.name, text=pin.default_text))
        elif pin.default_display:
            # A User Defined Enum's value by its display name, as the editor shows it and authors write it.
            output.append(PinOverride(pin.name, value=pin.default_display, alternatives=(pin.default_value,)))
        else:
            output.append(PinOverride(pin.name, value=pin.default_value))
    return tuple(output)


def _properties(node: LiveNode, hint: NodeDoc | None, adapter: SchemaAdapter = GENERIC_ADAPTER) -> NodeProperties:
    """Only properties the previous document authored are reported (live returns every editable one),
    unless the schema adapter reports the node's authored values itself."""
    reported = adapter.extract_properties(node, hint)
    if reported is not None:
        return reported
    if hint is None or node.properties is None:
        return NodeProperties()
    output = {}
    for container in ("node", "template"):
        live = node.property_container(container)
        wanted = getattr(hint.properties, container)
        output[container] = {key: thaw_json(live[key]) for key in wanted if key in live}
    return NodeProperties(output["node"], output["template"])


def _action(node: LiveNode, adapter: SchemaAdapter, self_class: str | None) -> str | None:
    """The action key as the document applied it (``K2:Min``) while it still names the node's action, else the
    extract form."""
    if adapter.keeps_authored_ids and node.doc_action and node.action_key:
        try:
            authored = adapter.normalize_action(node.doc_action, self_class=self_class, path="/Action")
        except AssetDocumentContractError:
            authored = None
        if actions_equal(authored, node.action_key):
            return node.doc_action
    return adapter.extract_action(node.action_key, self_class=self_class)


def _node(node: LiveNode, node_id: str, ids: Mapping[str, str], hint: NodeDoc | None,
          adapter: SchemaAdapter, self_class: str | None, include_defaults: bool = False) -> NodeDoc:
    action = None if node.implicit_role else _action(node, adapter, self_class)
    extras = {} if action or node.implicit_role else {"Class": node.class_path}
    if extras and node.extras.get("unresolved"):
        extras["Unresolved"] = node.extras["unresolved"]  # what it names that does not exist
    return NodeDoc(
        id=node_id, action=action, implicit=node.implicit_role, guid=node.guid,
        parent=ids.get(node.parent_guid) if node.parent_guid else None, position=node.position,
        # An implicit node (entry, result, output pose) is compared only when linked or overridden: default
        # values would make an untouched one part of the compared graph.
        pin_overrides=_overrides(node, adapter, include_defaults and not node.implicit_role),
        properties=_properties(node, hint, adapter),
        name=adapter.extract_name(node),
        comment=node.comment or None, extras=extras, user_pins=_node_user_pins(node, adapter),
        pin_types=adapter.node_pin_types(node),
        # A comment box's size; a node's pinned comment bubble (a comment box shows its text in the box).
        size=Size(*node.box_size) if node.box_size is not None and min(node.box_size) >= 1 else None,
        comment_bubble_visible=True if node.comment_bubble_visible and node.box_size is None else None,
    )


def _node_user_pins(node: LiveNode, adapter: SchemaAdapter) -> tuple[UserPin, ...] | None:
    pins = adapter.node_user_pins(node)
    return None if pins is None else tuple(UserPin(pin.name, pin.type) for pin in pins)


def _user_pin(pin, role: str = "") -> UserPin:
    # A function input's default is its pin's autogenerated default (K2Node_FunctionEntry sets the one from
    # the other): it is authored when it is not the type's zero value. A return node keeps the values of its
    # pins the same way; those are the node's PinOverrides, not the signature's.
    if role == "entry" and type_zero(pin.type) is not None:
        authored = pin.default_value and not is_type_zero(pin.type, pin.default_value)
    else:
        authored = pin.default_value and not pin.is_autogenerated_default
    return UserPin(pin.name, pin.type, pin.default_value if authored else None)


def _signature(nodes: list[LiveNode], graph_role: str, adapter: SchemaAdapter) -> Signature | None:
    implicit = {}
    for node in nodes:  # the first node of a role states the signature (extra return nodes share its pins)
        if node.implicit_role in ("entry", "result"):
            implicit.setdefault(node.implicit_role, node)
    if not implicit:
        return None
    pins = {}
    for role in ("entry", "result"):
        node = implicit.get(role)
        pins[role] = tuple(_user_pin(pin, role) for pin in (adapter.user_pins(node, graph_role) if node else ()))
    defaults = adapter.signature_flag_defaults(graph_role)
    live_flags = adapter.signature_flags(implicit["entry"]) if "entry" in implicit and defaults is not None else {}
    flags = {key: value for key, value in live_flags.items() if key in defaults and defaults[key] != value}
    if not pins["entry"] and not pins["result"] and not flags:
        return None
    return Signature(pins["entry"], pins["result"], flags)


def extract_graph(graph: LiveGraph, live: LiveAsset, *, graph_id: str, path: str, hint: GraphDoc | None = None,
                  adapter: SchemaAdapter = GENERIC_ADAPTER, owner: str | None = None,
                  self_class: str | None = None, name: str | None = None, include_defaults: bool = False) -> GraphDoc:
    nodes = [node for node in graph.nodes if not adapter.is_ignorable_live(node, graph)]
    ids = _assign_ids(nodes, hint, adapter)
    hint_nodes = {node.guid: node for node in (hint.nodes if hint else ()) if node.guid}
    docs = tuple(_node(node, ids[node.guid], ids, hint_nodes.get(node.guid), adapter, self_class, include_defaults)
                 for node in nodes)
    links = tuple(
        LinkDoc(Endpoint(ids[link.from_.node_guid], link.from_.pin_name), Endpoint(ids[link.to.node_guid], link.to.pin_name))
        for link in graph.links if link.from_.node_guid in ids and link.to.node_guid in ids)
    children = []
    live_children = live.children(graph.guid)
    base_names = [adapter.subgraph_name(child, graph.node(child.owner_node_guid) if child.owner_node_guid else None)
                  for child in live_children]
    # Sibling graphs may share a name (two transitions between the same states): " #n" tells them
    # apart, numbered in the order of their owner nodes, as a document numbers them.
    node_order = {node.guid: index for index, node in enumerate(graph.nodes)}
    groups: dict[str, list[int]] = {}
    for index, base in enumerate(base_names):
        groups.setdefault(base.casefold(), []).append(index)
    child_names = list(base_names)
    for indices in groups.values():
        if len(indices) < 2:
            continue
        ordered = sorted(indices, key=lambda index: node_order.get(live_children[index].owner_node_guid, len(node_order)))
        for ordinal, index in enumerate(ordered[1:], start=2):
            child_names[index] = f"{base_names[index]} #{ordinal}"
    for index, child in enumerate(live_children):
        child_name = child_names[index]
        child_hint = _hint_graph(child, hint.subgraphs, child_name) if hint else None
        children.append(extract_graph(
            child, live, graph_id=f"{graph_id}/{child_name}", path=f"{path}/Subgraphs/{index}", hint=child_hint,
            adapter=adapter, owner=ids.get(child.owner_node_guid) if child.owner_node_guid else None,
            self_class=self_class, name=child_name, include_defaults=include_defaults))
    entry = next((node for node in nodes if node.implicit_role == "entry"), None)
    return GraphDoc(id=graph_id, role=graph.role, name=graph.name if name is None else name,
                    schema_tag=graph.schema_tag, guid=graph.guid,
                    nodes=docs, links=links, subgraphs=tuple(children),
                    signature=_signature(nodes, graph.role, adapter), owner=owner, path=path,
                    local_variables=adapter.local_variables(entry) or None)


def extract_graphs(live: LiveAsset, *, sections: Mapping[str, str], hints: tuple[GraphDoc, ...] = (),
                   adapter: SchemaAdapter = GENERIC_ADAPTER, self_class: str | None = None,
                   include_defaults: bool = False) -> tuple[GraphDoc, ...]:
    """Extract every top-level live graph whose role maps to a Body section (role -> section key).

    ``self_class`` (the asset's generated class) lets member actions use the ``Self`` owner.
    ``include_defaults`` also reports pin values equal to the pin's default (see ``_overrides``).
    """
    counters: dict[str, int] = {}
    output = []
    for graph in live.graphs:
        section = sections.get(graph.role)
        if graph.parent_guid is not None or section is None:
            continue
        index = counters.get(section, 0)
        counters[section] = index + 1
        output.append(extract_graph(graph, live, graph_id=f"{section}/{graph.name}", path=f"/Body/{section}/{index}",
                                    hint=_hint_graph(graph, hints), adapter=adapter, self_class=self_class,
                                    include_defaults=include_defaults))
    return tuple(output)
