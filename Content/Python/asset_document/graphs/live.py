"""Typed decoding of ``graph.list.v1`` / ``graph.query.v1`` result values.

Follows docs/architecture/asset-document-graph-primitives.md section 3/4.
Required fields are strict; unknown result fields are tolerated so the native
side can add observations without breaking Python.  ``graph.query.v1`` results
are paginated per graph (``node_count`` / ``next_node_offset``);
``query_graphs`` follows the pages and merges them before decoding, and asks for
many graphs in chunks; ``list_graphs`` pages ``graph.list.v1`` by ``offset`` when
the whole list exceeds the runtime value budget.  Live models are
immutable snapshots: the executor replaces them after every re-query.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from types import MappingProxyType
from typing import Callable, Mapping

from asset_document.diagnostics import AssetDocumentContractError, contract_error
from asset_document.graphs.model import PinType, Position, freeze_json, normalize_guid
from asset_document.graphs.pin_names import resolve_pin_name


def _error(path: str, message: str):
    return contract_error(path, "Graph.InvalidSnapshot", message)


def _object(value: object, path: str) -> dict:
    if type(value) is not dict:
        raise _error(path, "Expected an object.")
    version = value.get("schema_version", 1)
    if version != 1 or type(version) is not int:
        raise _error(f"{path}/schema_version", "Only schema_version 1 is understood.")
    return value


def _list(value: object, path: str) -> list:
    if type(value) is not list:
        raise _error(path, "Expected an array.")
    return value


def _str(row: dict, key: str, path: str, *, optional: bool = False, default: str | None = "") -> str | None:
    value = row.get(key)
    if value is None:
        if optional:
            return default
        raise _error(f"{path}/{key}", "Required field is missing.")
    if type(value) is not str:
        raise _error(f"{path}/{key}", "Expected a string.")
    return value


def _bool(row: dict, key: str, path: str, default: bool = False) -> bool:
    value = row.get(key, default)
    if type(value) is not bool:
        raise _error(f"{path}/{key}", "Expected a boolean.")
    return value


def _guid(value: object, path: str) -> str | None:
    return normalize_guid(value, path, "Graph.InvalidSnapshot")


def _required_guid(row: dict, key: str, path: str) -> str:
    value = _guid(row.get(key), f"{path}/{key}")
    if value is None:
        raise _error(f"{path}/{key}", "A GUID is required.")
    return value


@dataclass(frozen=True, slots=True)
class LivePinRef:
    node_guid: str
    pin_name: str


@dataclass(frozen=True, slots=True)
class LivePin:
    name: str
    direction: str
    type: PinType
    default_value: str = ""
    default_object: str = ""
    default_text: str = ""
    is_autogenerated_default: bool = False
    hidden: bool = False
    advanced: bool = False
    orphaned: bool = False
    linked_to: tuple[LivePinRef, ...] = ()
    display_name: str = ""
    # An enum pin's value as the editor shows it, when it differs from the stored enumerator name.
    default_display: str = ""


@dataclass(frozen=True, slots=True)
class LiveNode:
    guid: str
    class_path: str
    action_key: str | None
    title: str
    implicit_role: str | None
    position: Position | None
    comment: str
    enabled_state: str
    parent_guid: str | None
    subnode_index: int | None
    subgraph_guids: tuple[str, ...]
    can_add_pin: bool
    extras: Mapping[str, object]
    pins: tuple[LivePin, ...]
    properties: Mapping[str, object] | None = None
    # The comment bubble is pinned open (SCommentBubble's toggle).
    comment_bubble_visible: bool = False
    # A resizable node's size (a comment box), (width, height).
    box_size: tuple[int, int] | None = None
    # The size the graph editor draws the node at (graph.query.v1 include_sizes), (width, height).
    widget_size: tuple[int, int] | None = None
    # The document Id and the action key as authored that the node was last applied with (package metadata
    # graph.finalize.v1 records), or None.
    doc_id: str | None = None
    doc_action: str | None = None

    def find_pin(self, name: str, direction: str | None = None) -> LivePin | None:
        """Exact name first, then case-insensitive, then the loose spellings of ``pin_names`` (a user
        struct member's name, a display name, a cast's ``Result``) when they pick one pin; ``direction``
        filters when given."""
        candidates = [pin for pin in self.pins if direction is None or pin.direction == direction]
        for pin in candidates:
            if pin.name == name:
                return pin
        folded = [pin for pin in candidates if pin.name.casefold() == name.casefold()]
        if folded:
            return folded[0] if len(folded) == 1 else None
        return resolve_pin_name(name, candidates, action=self.action_key, class_path=self.class_path)

    def property_container(self, container: str) -> Mapping[str, object]:
        if self.properties is None:
            return MappingProxyType({})
        value = self.properties.get(container, MappingProxyType({}))
        return value if isinstance(value, Mapping) else MappingProxyType({})


@dataclass(frozen=True, slots=True)
class LiveLink:
    from_: LivePinRef
    to: LivePinRef


@dataclass(frozen=True, slots=True)
class LiveGraph:
    guid: str
    path: str
    role: str
    schema_tag: str
    nodes: tuple[LiveNode, ...]
    links: tuple[LiveLink, ...]
    name: str = ""
    parent_guid: str | None = None
    owner_node_guid: str | None = None
    caps: Mapping[str, bool] = field(default_factory=lambda: MappingProxyType({}))

    def node(self, guid: str) -> LiveNode | None:
        for node in self.nodes:
            if node.guid == guid:
                return node
        return None

    def can(self, capability: str) -> bool:
        return bool(self.caps.get(capability, True))


@dataclass(frozen=True, slots=True)
class LiveGraphInfo:
    guid: str
    name: str
    path: str
    role: str
    schema_class: str
    schema_tag: str
    parent_guid: str | None
    owner_node_guid: str | None
    caps: Mapping[str, bool]


@dataclass(frozen=True, slots=True)
class LiveAsset:
    graphs: tuple[LiveGraph, ...] = ()
    # A Blueprint's ancestor classes, nearest first (graph.list ``class_chain``).
    class_chain: tuple[str, ...] = ()

    def graph(self, guid: str) -> LiveGraph | None:
        for graph in self.graphs:
            if graph.guid == guid:
                return graph
        return None

    def children(self, parent_guid: str | None) -> tuple[LiveGraph, ...]:
        return tuple(graph for graph in self.graphs if graph.parent_guid == parent_guid)

    def replace(self, graph: LiveGraph) -> "LiveAsset":
        if self.graph(graph.guid) is None:
            return LiveAsset(self.graphs + (graph,), self.class_chain)
        return LiveAsset(tuple(graph if item.guid == graph.guid else item for item in self.graphs), self.class_chain)


def _pin_type(value: object, path: str) -> PinType:
    row = _object(value, path)
    value_type = row.get("value_type")
    return PinType(
        category=_str(row, "category", path),
        sub_category=_str(row, "sub_category", path, optional=True),
        sub_category_object=_str(row, "sub_category_object", path, optional=True),
        container=_str(row, "container", path, optional=True, default="none"),
        is_ref=_bool(row, "is_ref", path),
        is_const=_bool(row, "is_const", path),
        value_type=None if value_type is None else _pin_type(
            dict(_object(value_type, f"{path}/value_type"), is_ref=False, is_const=False), f"{path}/value_type"),
    )


def decode_pin_type_dto(value: object, path: str) -> PinType:
    """A pin type DTO (``category`` / ``sub_category`` / ...) as a PinType."""
    return _pin_type(value, path)


def _pin_ref(value: object, path: str) -> LivePinRef:
    row = _object(value, path)
    return LivePinRef(_required_guid(row, "node_guid", path), _str(row, "pin_name", path))


def decode_pin(value: object, path: str) -> LivePin:
    row = _object(value, path)
    direction = _str(row, "direction", path)
    if direction not in ("input", "output"):
        raise _error(f"{path}/direction", "Pin direction must be input or output.")
    return LivePin(
        name=_str(row, "name", path), direction=direction, type=_pin_type(row.get("type"), f"{path}/type"),
        default_value=_str(row, "default_value", path, optional=True),
        default_object=_str(row, "default_object", path, optional=True),
        default_text=_str(row, "default_text", path, optional=True),
        is_autogenerated_default=_bool(row, "is_autogenerated_default", path),
        hidden=_bool(row, "hidden", path), advanced=_bool(row, "advanced", path),
        orphaned=_bool(row, "orphaned", path),
        linked_to=tuple(_pin_ref(item, f"{path}/linked_to/{index}")
                        for index, item in enumerate(_list(row.get("linked_to", []), f"{path}/linked_to"))),
        display_name=_str(row, "display_name", path, optional=True),
        default_display=_str(row, "default_display", path, optional=True),
    )


def _position(value: object, path: str) -> Position | None:
    if value is None:
        return None
    row = _object(value, path)
    try:
        return Position(row.get("x"), row.get("y"))
    except Exception:
        raise _error(path, "Position needs numeric x and y.") from None


def _size(value: object, path: str) -> tuple[int, int] | None:
    if value is None:
        return None
    row = _object(value, path)
    width, height = row.get("width"), row.get("height")
    if type(width) is not int or type(height) is not int:
        raise _error(path, "A size needs integer width and height.")
    return width, height


def decode_node(value: object, path: str) -> LiveNode:
    row = _object(value, path)
    subnode_index = row.get("subnode_index")
    if subnode_index is not None and type(subnode_index) is not int:
        raise _error(f"{path}/subnode_index", "Expected an integer or null.")
    extras = row.get("extras") or {}
    properties = row.get("properties")
    if type(extras) is not dict or (properties is not None and type(properties) is not dict):
        raise _error(path, "extras and properties must be objects.")
    return LiveNode(
        guid=_required_guid(row, "node_guid", path),
        class_path=_str(row, "class", path),
        action_key=_str(row, "action_key", path, optional=True, default=None) or None,
        title=_str(row, "title", path, optional=True),
        implicit_role=_str(row, "implicit_role", path, optional=True, default=None) or None,
        position=_position(row.get("position"), f"{path}/position"),
        comment=_str(row, "comment", path, optional=True),
        enabled_state=_str(row, "enabled_state", path, optional=True, default="enabled"),
        parent_guid=_guid(row.get("parent_node_guid"), f"{path}/parent_node_guid"),
        subnode_index=subnode_index,
        subgraph_guids=tuple(_guid(item, f"{path}/subgraph_guids/{index}") for index, item in
                             enumerate(_list(row.get("subgraph_guids", []), f"{path}/subgraph_guids"))),
        can_add_pin=_bool(row, "can_add_pin", path),
        extras=freeze_json(extras, f"{path}/extras"),
        pins=tuple(decode_pin(item, f"{path}/pins/{index}")
                   for index, item in enumerate(_list(row.get("pins", []), f"{path}/pins"))),
        properties=None if properties is None else freeze_json(properties, f"{path}/properties"),
        comment_bubble_visible=_bool(row, "comment_bubble_visible", path),
        box_size=_size(row.get("box_size"), f"{path}/box_size"),
        widget_size=_size(row.get("widget_size"), f"{path}/widget_size"),
        doc_id=_str(row, "doc_id", path, optional=True, default=None) or None,
        doc_action=_str(row, "doc_action", path, optional=True, default=None) or None,
    )


def decode_graph_snapshot(value: object, path: str = "/graphs/0", info: LiveGraphInfo | None = None) -> LiveGraph:
    row = _object(value, path)
    nodes = tuple(decode_node(item, f"{path}/nodes/{index}")
                  for index, item in enumerate(_list(row.get("nodes", []), f"{path}/nodes")))
    links = []
    for index, item in enumerate(_list(row.get("links", []), f"{path}/links")):
        link = _object(item, f"{path}/links/{index}")
        links.append(LiveLink(_pin_ref(link.get("from"), f"{path}/links/{index}/from"),
                              _pin_ref(link.get("to"), f"{path}/links/{index}/to")))
    graph_path = _str(row, "path", path)
    return LiveGraph(
        guid=_required_guid(row, "graph_guid", path), path=graph_path, role=_str(row, "role", path),
        schema_tag=_str(row, "schema_tag", path), nodes=nodes, links=tuple(links),
        name=info.name if info else graph_path.rsplit("/", 1)[-1],
        parent_guid=info.parent_guid if info else None,
        owner_node_guid=info.owner_node_guid if info else None,
        caps=info.caps if info else MappingProxyType({}),
    )


def decode_graph_list(value: object) -> tuple[LiveGraphInfo, ...]:
    row = _object(value, "/")
    output = []
    for index, item in enumerate(_list(row.get("graphs"), "/graphs")):
        path = f"/graphs/{index}"
        graph = _object(item, path)
        caps = graph.get("caps", {})
        if type(caps) is not dict or any(type(flag) is not bool for flag in caps.values()):
            raise _error(f"{path}/caps", "caps must map capability names to booleans.")
        output.append(LiveGraphInfo(
            guid=_required_guid(graph, "graph_guid", path), name=_str(graph, "name", path),
            path=_str(graph, "path", path), role=_str(graph, "role", path),
            schema_class=_str(graph, "schema_class", path, optional=True),
            schema_tag=_str(graph, "schema_tag", path),
            parent_guid=_guid(graph.get("parent_graph_guid"), f"{path}/parent_graph_guid"),
            owner_node_guid=_guid(graph.get("owner_node_guid"), f"{path}/owner_node_guid"),
            caps=MappingProxyType(dict(caps)),
        ))
    return tuple(output)


def list_graphs(invoke: Callable[[dict], object]) -> tuple[LiveGraphInfo, ...]:
    """``graph.list.v1`` through ``invoke(value_arguments)``.

    The whole list in one call; when the runtime value budget refuses it (an asset with
    hundreds of graphs), the list is read in ``offset`` pages until ``next_offset`` is null.
    """
    try:
        return decode_graph_list(invoke({}))
    except AssetDocumentContractError as error:
        if error.diagnostic.code != "Graph.ResultTooLarge":
            raise
    infos: list[LiveGraphInfo] = []
    offset: int | None = 0
    pages = 0
    while offset is not None:
        pages += 1
        if pages > MAX_QUERY_PAGES:
            raise _error("/next_offset", "graph.list pagination did not terminate.")
        page = _object(invoke({"offset": offset}), "/")
        rows = decode_graph_list(page)
        following = page.get("next_offset")
        if following is not None and (type(following) is not int or following <= offset or not rows):
            raise _error("/next_offset", "graph.list pagination made no progress.")
        infos.extend(rows)
        offset = following
    return tuple(infos)


def decode_query(value: object, infos: tuple[LiveGraphInfo, ...] = ()) -> tuple[LiveGraph, ...]:
    row = _object(value, "/")
    by_guid = {info.guid: info for info in infos}
    graphs = []
    for index, item in enumerate(_list(row.get("graphs"), "/graphs")):
        guid = normalize_guid(item.get("graph_guid") if type(item) is dict else None, f"/graphs/{index}/graph_guid",
                              "Graph.InvalidSnapshot")
        graphs.append(decode_graph_snapshot(item, f"/graphs/{index}", by_guid.get(guid)))
    return tuple(graphs)


MAX_QUERY_PAGES = 4096
# Graphs per graph.query.v1 call when every graph of a large asset is read.
QUERY_GRAPH_CHUNK = 64


def _next_offset(row: dict, path: str) -> int | None:
    value = row.get("next_node_offset")
    if value is not None and (type(value) is not int or value < 0):
        raise _error(f"{path}/next_node_offset", "Expected a non-negative integer or null.")
    return value


def merge_graph_pages(pages: list[dict]) -> dict:
    """Merge the pages of one graph into a single complete snapshot row.

    Each page carries the nodes ``[node_offset, next_node_offset)`` and the
    output-side links of those nodes, so the union is complete; duplicates
    (by node GUID / link endpoints) are dropped defensively.
    """
    first = dict(pages[0])
    nodes, seen_nodes, links, seen_links = [], set(), [], set()
    for index, page in enumerate(pages):
        for node in _list(page.get("nodes", []), f"/graphs/{index}/nodes"):
            key = str(node.get("node_guid", "")).upper() if type(node) is dict else None
            if key is None or key not in seen_nodes:
                seen_nodes.add(key)
                nodes.append(node)
        for link in _list(page.get("links", []), f"/graphs/{index}/links"):
            try:
                key = tuple(str(link[side][part]).upper() if part == "node_guid" else link[side][part]
                            for side in ("from", "to") for part in ("node_guid", "pin_name"))
            except (KeyError, TypeError):
                key = None  # malformed: let decoding report it
            if key is None or key not in seen_links:
                seen_links.add(key)
                links.append(link)
    first.update(nodes=nodes, links=links, next_node_offset=None)
    return first


def query_graphs(query: Callable[[dict], object], *, graphs: list | None = None, include_properties: bool = False,
                 infos: tuple[LiveGraphInfo, ...] = (), include_sizes: bool = False) -> tuple[LiveGraph, ...]:
    """Run ``graph.query.v1`` through ``query(value_arguments)`` and follow per-graph pagination.

    A snapshot with a non-null ``next_node_offset`` is continued by querying
    that graph alone from the given offset until the offset is null.  Without
    ``graphs`` but with more than ``QUERY_GRAPH_CHUNK`` ``infos`` (every graph of
    the asset, from ``list_graphs``), the graphs are asked for in chunks: each
    requested graph reports a header, so hundreds of them exceed the budget.
    """
    if graphs is None and len(infos) > QUERY_GRAPH_CHUNK:
        output: list[LiveGraph] = []
        for start in range(0, len(infos), QUERY_GRAPH_CHUNK):
            chunk = infos[start:start + QUERY_GRAPH_CHUNK]
            output.extend(query_graphs(query, graphs=[{"graph_guid": info.guid} for info in chunk],
                                       include_properties=include_properties, infos=chunk, include_sizes=include_sizes))
        return tuple(output)
    values: dict = {"include_properties": include_properties}
    if include_sizes:
        values["include_sizes"] = True
    if graphs is not None:
        values["graphs"] = graphs
    first = _object(query(values), "/")
    rows = _list(first.get("graphs"), "/graphs")
    by_guid = {info.guid: info for info in infos}
    output = []
    for index, row in enumerate(rows):
        path = f"/graphs/{index}"
        row = _object(row, path)
        guid = _required_guid(row, "graph_guid", path)
        pages, offset = [row], _next_offset(row, path)
        while offset is not None:
            if len(pages) >= MAX_QUERY_PAGES:
                raise _error(path, "graph.query pagination did not terminate.")
            page_request = {"graphs": [{"graph_guid": guid}], "include_properties": include_properties,
                            "node_offset": offset}
            if include_sizes:
                page_request["include_sizes"] = True
            page_value = _object(query(page_request), "/")
            page_rows = _list(page_value.get("graphs"), "/graphs")
            if len(page_rows) != 1:
                raise _error("/graphs", "graph.query must return exactly the requested graph.")
            page = _object(page_rows[0], "/graphs/0")
            if _required_guid(page, "graph_guid", "/graphs/0") != guid:
                raise _error("/graphs/0/graph_guid", "graph.query returned a different graph.")
            following = _next_offset(page, "/graphs/0")
            if following is not None and following <= offset:
                raise _error("/graphs/0/next_node_offset", "graph.query pagination made no progress.")
            pages.append(page)
            offset = following
        merged = merge_graph_pages(pages) if len(pages) > 1 else row
        output.append(decode_graph_snapshot(merged, path, by_guid.get(guid)))
    return tuple(output)


def decode_class_chain(list_value: object) -> tuple[str, ...]:
    """A Blueprint's ancestor classes from a graph.list result (empty for other assets)."""
    row = _object(list_value, "/")
    chain = row.get("class_chain", [])
    if type(chain) is not list or any(type(item) is not str for item in chain):
        raise _error("/class_chain", "class_chain must be an array of class paths.")
    return tuple(chain)


def decode_live_asset(list_value: object, query_value: object) -> LiveAsset:
    """Merge a graph.list result (names, ownership, caps) with a graph.query result."""
    return LiveAsset(decode_query(query_value, decode_graph_list(list_value)), decode_class_chain(list_value))
