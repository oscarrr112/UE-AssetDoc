"""Shared helpers for graph tests: real captured DTO fixtures and a stateful fake graph provider.

The fixtures under ``fixtures/graph_dto`` are outputs captured from the C++
provider (Source/AssetDocumentGraph).  Node templates of the fake provider are
taken from those captures wherever one exists, so executor tests see the real
pin names, pin types, extras and enabled states.
"""
from __future__ import annotations

from copy import deepcopy
import json
import os

from asset_document.diagnostics import DiagnosticContext, RuntimeDiagnostic
from asset_document.graphs.live import decode_live_asset
from asset_document.regions.primitive_catalog import PrimitiveOutcome, PrimitiveOutcomeStatus


FIXTURES = os.path.join(os.path.dirname(__file__), "fixtures", "graph_dto")
ACTOR_CLASS = "/Game/BP_Test.BP_Test_C"
KSL = "/Script/Engine.KismetSystemLibrary"
PRINT = f"K2:CallFunction:{KSL}:PrintString"
BEGIN_PLAY = "K2:Event:/Script/Engine.Actor:ReceiveBeginPlay"
RANDOM_BOOL = "K2:CallFunction:/Script/Engine.KismetMathLibrary:RandomBool"
G_EVENT, G_UCS, G_FUNC = "A0000000000000000000000000000001", "A0000000000000000000000000000002", "A0000000000000000000000000000003"
N_BEGIN, N_OVERLAP, N_TICK, N_BRANCH, N_PRINT = ("B00000000000000000000000000000%02d" % i for i in range(1, 6))
N_ENTRY, N_RESULT = "D0000000000000000000000000000001", "D0000000000000000000000000000002"


def fixture(name: str):
    with open(os.path.join(FIXTURES, name), encoding="utf-8") as handle:
        return json.load(handle)


def live_asset(query: str, listing: str = "graph.list.v1.k2_empty_actor.json"):
    return decode_live_asset(fixture(listing), fixture(query))


def ptype(category, sub="", obj="", container="none"):
    return {"category": category, "sub_category": sub, "sub_category_object": obj, "container": container,
            "is_ref": False, "is_const": False}


def pin(name, direction, type_, default="", obj="", autogen=True, hidden=False):
    return {"name": name, "direction": direction, "type": type_, "default_value": default, "default_object": obj,
            "default_text": "", "is_autogenerated_default": autogen, "hidden": hidden, "advanced": False,
            "orphaned": False, "linked_to": []}


EXEC = ptype("exec")
WILDCARD = ptype("wildcard")


def _template(action, implicit=None, can_add_pin=False, *pins):
    return {"action_key": action, "implicit_role": implicit, "can_add_pin": can_add_pin, "pins": list(pins)}


def _captured(query, node_guid, *, keep_user_pins=False):
    """A node template from a captured query fixture: links cleared, ghost state and user pins dropped."""
    for graph in fixture(query)["graphs"]:
        for node in graph["nodes"]:
            if node["node_guid"] != node_guid:
                continue
            node = deepcopy(node)
            node["extras"].pop("ghost", None)
            if node["enabled_state"] == "disabled":
                node["enabled_state"] = "enabled"
            user = set(node["extras"].get("user_pins", ()))
            if "user_pins" in node["extras"] and not keep_user_pins:
                node["pins"] = [item for item in node["pins"] if item["name"] not in user]
                node["extras"]["user_pins"] = []
            for item in node["pins"]:
                item["linked_to"] = []
                if not item["is_autogenerated_default"] and not item["hidden"]:
                    item["default_value"], item["is_autogenerated_default"] = "Hello", True  # PrintString InString
            return node
    raise KeyError(node_guid)


SIGNATURE_QUERY = "graph.query.v1.k2_function_signature.json"
TEMPLATES = {
    "K2:IfThenElse": fixture("graph.node.spawn.v1.k2_branch.json")["node"],
    PRINT: _captured("graph.query.v1.k2_branch.json", N_PRINT),
    BEGIN_PLAY: _captured("graph.query.v1.k2_empty_actor.json", N_BEGIN),
    "K2:FunctionEntry": _captured(SIGNATURE_QUERY, N_ENTRY),
    "K2:FunctionResult": _captured(SIGNATURE_QUERY, N_RESULT),
    "K2:Select": {**_template("K2:Select", None, True, pin("Option 0", "input", WILDCARD),
                              pin("Option 1", "input", WILDCARD), pin("Index", "input", ptype("wildcard", "index")),
                              pin("ReturnValue", "output", WILDCARD)),
                  "extras": {"typed_pins": ["Index"]}},
    RANDOM_BOOL: _template(RANDOM_BOOL, None, False, pin("ReturnValue", "output", ptype("bool"))),
    "K2:ExecutionSequence": _template("K2:ExecutionSequence", None, True, pin("execute", "input", EXEC),
                                      pin("then_0", "output", EXEC), pin("then_1", "output", EXEC)),
}


def ok(value):
    return PrimitiveOutcome(PrimitiveOutcomeStatus.SUCCEEDED, value, (), (), ())


def failed(path, code, message):
    return PrimitiveOutcome(PrimitiveOutcomeStatus.FAILED, None, (), (), (RuntimeDiagnostic(path, code, message),))


class FakeGraphContext:
    """In-memory graph provider honouring the v1 DTO shapes closely enough for executor tests."""

    def __init__(self, listing: str, query: str, *, page_size: int | None = None, too_large_above: int | None = None):
        infos = fixture(listing)["graphs"]
        snapshots = {row["graph_guid"]: row for row in fixture(query)["graphs"]}
        self.graphs = {}
        for info in infos:
            snapshot = snapshots[info["graph_guid"]]
            self.graphs[info["graph_guid"]] = {
                "info": deepcopy(info), "nodes": deepcopy(snapshot["nodes"]),
                "links": [(l["from"]["node_guid"], l["from"]["pin_name"], l["to"]["node_guid"], l["to"]["pin_name"])
                          for l in snapshot["links"]]}
        self.calls = []
        self.counter = 0
        self.finalize_value = {"status": "ok", "messages": []}
        # Flags a new function's entry starts with besides the template's (an editor utility Blueprint: Call In Editor).
        self.new_function_flags = {}
        # Action keys of nodes a new function comes with (an override's "Parent: <function>" call).
        self.new_function_placed = []
        self.finalize_failure = None
        # Runtime value budget emulation: page_size nodes per graph page (truncated=true),
        # too_large_above refuses queries whose node_limit is absent or larger (Graph.ResultTooLarge).
        self.page_size = page_size
        self.too_large_above = too_large_above

    # Helpers -------------------------------------------------------------
    def calls_of(self, primitive):
        return [args for name, args in self.calls if name == primitive]

    def primitive_sequence(self):
        return [name for name, _ in self.calls]

    def _new_guid(self, prefix="E"):
        self.counter += 1
        return f"{prefix}{self.counter:031X}"

    def _find(self, node_guid):
        for graph in self.graphs.values():
            for node in graph["nodes"]:
                if node["node_guid"] == node_guid:
                    return graph, node
        return None, None

    def _pin(self, ref):
        graph, node = self._find(ref["node_guid"])
        if node is None:
            return None, None, None
        found = next((p for p in node["pins"] if p["name"] == ref["pin_name"] and p["direction"] == ref["direction"]), None)
        return graph, node, found

    def _snapshot(self, guid, offset=0, limit=None):
        """Like the C++ handler: a node page plus the output-side links of the page's nodes."""
        graph = self.graphs[guid]
        nodes = deepcopy(graph["nodes"])
        by_guid = {node["node_guid"]: node for node in nodes}
        for node in nodes:
            for item in node["pins"]:
                item["linked_to"] = []
        for a, ap, b, bp in graph["links"]:
            for (src, src_pin, dst, dst_pin, direction) in ((a, ap, b, bp, "output"), (b, bp, a, ap, "input")):
                node = by_guid.get(src)
                for item in node["pins"] if node else ():
                    if item["name"] == src_pin and item["direction"] == direction:
                        item["linked_to"].append({"node_guid": dst, "pin_name": dst_pin})
        size = min(limit or len(nodes), self.page_size or len(nodes)) or 1
        page = nodes[offset:offset + size]
        end = offset + len(page)
        guids = {node["node_guid"] for node in page}
        info = graph["info"]
        return {"schema_version": 1, "graph_guid": guid, "path": info["path"], "role": info["role"],
                "schema_tag": "K2", "node_count": len(nodes), "next_node_offset": end if end < len(nodes) else None,
                "nodes": page,
                "links": [{"from": {"node_guid": a, "pin_name": ap}, "to": {"node_guid": b, "pin_name": bp}}
                          for a, ap, b, bp in graph["links"] if a in guids]}

    # Protocol --------------------------------------------------------------
    def invoke(self, *, requirement, value_arguments, handle_arguments):
        name = requirement.primitive_id
        assert value_arguments.get("schema_version") == 1, name
        assert [item.name for item in handle_arguments] == ["asset"], name
        self.calls.append((name, deepcopy(value_arguments)))
        handler = getattr(self, "_" + name.replace(".", "_"))
        return handler(value_arguments)

    def _graph_list_v1(self, args):
        return ok({"schema_version": 1, "graphs": [deepcopy(g["info"]) for g in self.graphs.values()]})

    def _graph_query_v1(self, args):
        if self.too_large_above is not None and args.get("node_limit", 1 << 30) > self.too_large_above:
            return failed("/value_arguments", "Graph.ResultTooLarge", "Result exceeds the runtime value budget.")
        guids = [row["graph_guid"] for row in args.get("graphs", [])] or list(self.graphs)
        snapshots = [self._snapshot(guid, args.get("node_offset", 0), args.get("node_limit")) for guid in guids]
        truncated = any(item["next_node_offset"] is not None for item in snapshots)
        return ok({"schema_version": 1, "graphs": snapshots, "truncated": truncated})

    def _graph_create_v1(self, args):
        guid = self._new_guid("F")
        parent = args.get("parent", {}).get("graph_guid")
        self.graphs[guid] = {"info": {"graph_guid": guid, "name": args["name"], "path": args["name"], "role": args["role"],
                                      "schema_class": "", "schema_tag": "K2", "parent_graph_guid": parent,
                                      "owner_node_guid": None, "caps": {"spawn": True, "rename": True, "remove": True}},
                             "nodes": [], "links": []}
        if args["role"] == "function":
            entry = self._make_node(TEMPLATES["K2:FunctionEntry"], {"x": 0, "y": 0})
            entry["extras"]["name"] = entry["title"] = args["name"]
            entry["extras"].setdefault("signature_flags", {}).update(self.new_function_flags)
            self.graphs[guid]["nodes"].append(entry)
            for action_key in self.new_function_placed:
                self.graphs[guid]["nodes"].append(self._make_node(
                    {"action_key": action_key, "implicit_role": None, "can_add_pin": False, "pins": []}, None))
        return ok({"schema_version": 1, "graph_guid": guid, "path": args["name"]})

    def _make_node(self, template, position):
        node = {"class": "/Script/BlueprintGraph.K2Node",
                "action_key": template["action_key"], "title": template["action_key"],
                "implicit_role": template["implicit_role"], "position": {"x": 0, "y": 0}, "comment": "",
                "enabled_state": "enabled", "parent_node_guid": None, "subnode_index": None, "subgraph_guids": [],
                "can_add_pin": template["can_add_pin"], "extras": {}}
        node.update(deepcopy({key: value for key, value in template.items() if key != "node_guid"}))
        node["node_guid"] = self._new_guid()
        node["position"] = position or {"x": 0, "y": 0}
        return node

    @staticmethod
    def _make_real(node):
        if node["extras"].pop("ghost", None):
            node["enabled_state"] = "enabled"
            node["comment"] = ""
            node.pop("comment_bubble_visible", None)

    def _graph_node_spawn_v1(self, args):
        if args["action_key"].startswith("K2:Event:"):
            # One event node per event per Blueprint: the existing (ghost) node is reused.
            for graph in self.graphs.values():
                for node in graph["nodes"]:
                    if node["action_key"] == args["action_key"]:
                        self._make_real(node)
                        if "position" in args:
                            node["position"] = args["position"]
                        return ok({"schema_version": 1, "node_guid": node["node_guid"], "created_node_guids": [],
                                   "created_graph_guids": [], "reused": True, "node": deepcopy(node)})
        template = TEMPLATES.get(args["action_key"])
        if template is None:
            return failed("/value_arguments/action_key", "Graph.ActionNotFound", f"Unknown action {args['action_key']}")
        node = self._make_node(template, args.get("position"))
        self.graphs[args["graph"]["graph_guid"]]["nodes"].append(node)
        return ok({"schema_version": 1, "node_guid": node["node_guid"], "created_node_guids": [],
                   "created_graph_guids": [], "reused": False, "node": deepcopy(node)})

    def _graph_node_remove_v1(self, args):
        graph, node = self._find(args["node_guid"])
        graph["nodes"].remove(node)
        graph["links"] = [l for l in graph["links"] if args["node_guid"] not in (l[0], l[2])]
        return ok({"schema_version": 1, "removed_node_guids": [args["node_guid"]], "removed_graph_guids": []})

    def _graph_pin_connect_v1(self, args):
        graph, source_node, source = self._pin(args["from"])
        _, target_node, target = self._pin(args["to"])
        if source is None or target is None:
            return failed("/value_arguments/from", "Graph.PinNotFound", "Pin not found")
        categories = {source["type"]["category"], target["type"]["category"]}
        if "wildcard" not in categories and len(categories) != 1:
            return failed("/value_arguments/to", "Graph.ConnectDisallowed",
                          f"{source['type']['category']} is not compatible with {target['type']['category']}")
        graph["links"].append((source_node["node_guid"], source["name"], target_node["node_guid"], target["name"]))
        self._make_real(source_node)
        self._make_real(target_node)
        reconstructed = []
        if target_node["action_key"] == "K2:Select" and target["name"] == "Index":
            # K2Node_Select reconstructs with a bool index and renames its option pins.
            for item, new_name in zip(target_node["pins"][:2], ("False", "True")):
                item["name"] = new_name
            target["type"] = deepcopy(source["type"])
            reconstructed.append(target_node["node_guid"])
        return ok({"schema_version": 1, "response": "make", "created_node_guids": [], "broken_links": [],
                   "reconstructed_node_guids": reconstructed})

    def _graph_pin_break_v1(self, args):
        graph, node, _ = self._pin(args["from"])
        key = (args["from"]["node_guid"], args["from"]["pin_name"], args["to"]["node_guid"], args["to"]["pin_name"])
        graph["links"] = [l for l in graph["links"] if l != key]
        return ok({"schema_version": 1, "broken_links": []})

    def _graph_pin_default_set_v1(self, args):
        _, _, found = self._pin(args["pin"])
        if found is None:
            return failed("/value_arguments/pin", "Graph.PinNotFound", "Pin not found")
        field = {"value": "default_value", "object": "default_object", "text": "default_text"}.get(args["kind"])
        if field is None:
            found["default_value"], found["is_autogenerated_default"] = "", True
        else:
            found[field], found["is_autogenerated_default"] = args["value"], False
        return ok({"schema_version": 1, "default_value": found["default_value"],
                   "default_object": found["default_object"], "default_text": found["default_text"]})

    def _graph_node_layout_set_v1(self, args):
        _, node = self._find(args["node_guid"])
        if "position" in args:
            node["position"] = args["position"]
        if "comment" in args:
            node["comment"] = args["comment"]
        return ok({"schema_version": 1})

    def _graph_node_user_pins_set_v1(self, args):
        _, node = self._find(args["node_guid"])
        user = set(node["extras"].get("user_pins", ()))
        node["pins"] = [p for p in node["pins"] if p["name"] not in user] + [
            pin(item["name"], item["direction"], item["type"], item.get("default", ""), autogen="default" not in item)
            for item in args["pins"]]
        node["extras"]["user_pins"] = [item["name"] for item in args["pins"]]
        return ok({"schema_version": 1, "node": deepcopy(node)})

    def _graph_function_flags_set_v1(self, args):
        graph = self.graphs[args["graph"]["graph_guid"]]
        entry = next(node for node in graph["nodes"] if node["implicit_role"] == "entry")
        entry["extras"]["signature_flags"].update(args["flags"])
        return ok({"schema_version": 1, "flags": deepcopy(entry["extras"]["signature_flags"])})

    def _graph_node_pin_type_set_v1(self, args):
        # UK2Node_Select: an enum index makes one option pin per enumerator (the fake enum has two).
        _, node = self._find(args["node_guid"])
        found = next((p for p in node["pins"] if p["name"] == args["pin_name"]), None)
        if found is None:
            return failed("/value_arguments/pin_name", "Graph.PinNotFound", "Pin not found")
        if args["pin_name"] not in node["extras"].get("typed_pins", ()) or found["type"]["category"] != "wildcard":
            return failed("/value_arguments/pin_name", "Graph.PinTypeNotEditable", "Pin type is not editable")
        found["type"] = deepcopy(args["type"])
        if args["type"]["sub_category_object"]:
            options = [p for p in node["pins"] if p["name"].startswith("Option ")]
            for index, item in enumerate(options):
                item["name"] = f"NewEnumerator{index}"
        return ok({"schema_version": 1, "node": deepcopy(node)})

    def _graph_node_dynamic_pin_add_v1(self, args):
        _, node = self._find(args["node_guid"])
        count = sum(1 for p in node["pins"] if p["name"].startswith("then_"))
        node["pins"].append(pin(f"then_{count}", "output", EXEC))
        return ok({"schema_version": 1, "node": deepcopy(node)})

    def _graph_node_property_set_v1(self, args):
        return ok({"schema_version": 1, "value": args["value"]})

    def _graph_node_rename_v1(self, args):
        return ok({"schema_version": 1, "name": args["name"]})

    def _graph_remove_v1(self, args):
        del self.graphs[args["graph"]["graph_guid"]]
        return ok({"schema_version": 1, "removed_graph_guids": [args["graph"]["graph_guid"]]})

    def _graph_finalize_v1(self, args):
        # Node document identity, recorded as the C++ primitive does (package metadata), before compiling.
        for item in args.get("node_meta", ()):
            _, node = self._find(item["node_guid"])
            node["doc_id"] = item["id"]
            if item.get("action"):
                node["doc_action"] = item["action"]
            else:
                node.pop("doc_action", None)
        if args.get("compile") is False:
            return ok({"status": "recorded", "messages": []})
        if self.finalize_failure is not None:
            # The C++ primitive fails on compile errors and carries the compiler messages in its error context.
            return PrimitiveOutcome(PrimitiveOutcomeStatus.FAILED, None, (), (), (RuntimeDiagnostic(
                "/PrimitiveOutcome", "Graph.FinalizeFailed", "Finalize reported errors",
                context=(DiagnosticContext("messages", deepcopy(self.finalize_failure)),)),))
        return ok(deepcopy(self.finalize_value))
