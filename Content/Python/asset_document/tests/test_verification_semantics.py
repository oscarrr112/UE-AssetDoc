from asset_document.graphs.schemas import k2
from asset_document.profiles.ublueprint_graph_compare import section_mismatch_reasons
from asset_document.tests.graph_support import ACTOR_CLASS, fixture

EMPTY = ("graph.query.v1.k2_empty_actor.json", "graph.list.v1.k2_empty_actor.json")
SIGNATURE = ("graph.query.v1.k2_function_signature.json", "graph.list.v1.k2_function.json")
TICK_GUID = "B0000000000000000000000000000003"
ENTRY_GUID = "D0000000000000000000000000000001"
RESULT_GUID = "D0000000000000000000000000000002"
FUNC = "FunctionGraphs/AddHealth"


def _type(category, sub=""):
    return {"category": category, "sub_category": sub, "sub_category_object": "", "container": "none",
            "is_ref": False, "is_const": False}


def _pin(name, direction, category, sub="", default="", autogen=True, linked=()):
    return {"name": name, "direction": direction, "type": _type(category, sub), "default_value": default,
            "default_object": "", "default_text": "", "is_autogenerated_default": autogen, "hidden": False,
            "advanced": False, "orphaned": False, "linked_to": [{"node_guid": g, "pin_name": p} for g, p in linked]}


def _node(value, guid):
    return next(node for graph in value["graphs"] for node in graph["nodes"] if node["node_guid"] == guid)


def _graph(value, path):
    return next(graph for graph in value["graphs"] if graph["path"] == path)


def _live(case, edit=None):
    value = deepcopy(fixture(case[0]))
    if edit is not None:
        edit(value)
    return decode_live_asset(fixture(case[1]), value)


def _plan(body, case, edit=None):
    graphs, roles = k2.decode_body(body, self_class=ACTOR_CLASS)
    return reconcile(graphs, _live(case, edit), managed_roles=roles, adapter=k2.K2_ADAPTER, self_class=ACTOR_CLASS,
                     role_paths={role: f"/Body/{s}" for s, role in k2.SECTIONS})


def _extract(live, include_defaults=False):
    return k2.encode_body(extract_graphs(live, sections=k2.SECTION_BY_ROLE, adapter=k2.K2_ADAPTER,
                                         self_class=ACTOR_CLASS, include_defaults=include_defaults))


class SemanticCompareTests(unittest.TestCase):
    def test_numbers_compare_within_float32(self):
        self.assertTrue(sc.same_number(0.8, 0.800000011920929))
        self.assertTrue(sc.same_number(1.3, 1.2999999523162842))
        self.assertFalse(sc.same_number(0.8, 0.81))
        self.assertTrue(sc.same_scalar_text("1.0", "1.000000"))
        self.assertTrue(sc.same_scalar_text("True", "true"))
        self.assertFalse(sc.same_scalar_text("1.0", "1.5"))
        self.assertTrue(sc.same_value({"A": [0.8, True]}, {"A": [0.800000011920929, True]}))
        self.assertFalse(sc.same_value(True, 1))

    def test_as_authored_keeps_the_members_the_document_states(self):
        observed = {"Meshes": [{"Mesh": "/Cube", "Scale": {"X": 1, "Y": 1, "Z": 1}, "LODBias": 0}]}
        self.assertEqual(sc.as_authored({"Meshes": [{"Mesh": "/Cube"}]}, observed), {"Meshes": [{"Mesh": "/Cube"}]})
        # A list of another length is not projected (an element was added or removed).
        self.assertEqual(sc.as_authored({"Meshes": []}, observed), {"Meshes": observed["Meshes"]})

    def test_first_difference_follows_keys_and_keeps_the_whole_element(self):
        expected = [{"Name": "Boom", "AttachTo": "Capsule", "Arm": 350.8}, {"Name": "Camera", "AttachTo": "Boom"}]
        actual = [{"Name": "Camera", "AttachTo": "Boom"}, {"Name": "Boom", "AttachTo": "Capsule", "Arm": 300.0}]
        self.assertEqual(sc.first_difference("/Body/Components", expected, actual),
                         ("/Body/Components/0/Arm", 350.8, 300.0))
        path, mine, theirs = sc.first_difference("/P", {"A": 0.8, "B": [1, 2]}, {"A": 0.800000011920929, "B": [1, 3]})
        self.assertEqual((path, mine, theirs), ("/P/B/1", 2, 3))
        self.assertNotIn("more", sc.describe({"Name": "x" * 900}))
        # Members only the read-back states are not the difference; a member the document states and the
        # read-back lacks is.
        self.assertEqual(sc.first_difference("/C", {"Name": "A", "Fov": 90}, {"Name": "A", "Fov": 80, "Aspect": 1.7}),
                         ("/C/Fov", 90, 80))
        self.assertEqual(sc.first_difference("/C", {"Name": "A", "Fov": 90}, {"Name": "A"}), ("/C/Fov", 90, sc.ABSENT))
        self.assertEqual(sc.describe(sc.ABSENT), "(absent)")

    def test_match_by_key_prefers_an_equal_item(self):
        pairs, extra = sc.match_by_key([{"k": 1, "v": "b"}, {"k": 1, "v": "a"}], [{"k": 1, "v": "a"}, {"k": 1, "v": "b"}],
                                       key=lambda item: item["k"], equal=lambda a, b: a == b)
        self.assertEqual((pairs, extra), ([(0, 1), (1, 0)], []))


class BlueprintGraphVerificationTests(unittest.TestCase):
    def test_custom_event_with_empty_inputs_matches_a_read_back_without_inputs(self):
        # "Inputs": [] states no parameters; extract leaves an empty list out.
        authored = [{"Name": "EventGraph", "Nodes": [{"Id": "Ev", "Action": "K2:CustomEvent", "Name": "EvStart",
                                                      "Inputs": []}]}]
        extracted = [{"Name": "EventGraph", "Nodes": [{"Id": "Ev", "Action": "K2:CustomEvent", "Name": "EvStart"}]}]
        self.assertEqual(section_mismatch_reasons("UbergraphPages", authored, extracted, self_class=ACTOR_CLASS), {})
        with_input = deepcopy(extracted)
        with_input[0]["Nodes"][0]["Inputs"] = [{"Name": "Power", "Type": "float"}]
        self.assertIn("EventGraph", section_mismatch_reasons("UbergraphPages", authored, with_input, self_class=ACTOR_CLASS))

    def test_signature_defaults_compare_as_numbers_and_type_zero(self):
        # Default "1.0" against a stored 1.000000; "0.0" against a read-back without Default.
        def function(inputs):
            return [{"Name": "Move", "Signature": {"Inputs": inputs}}]
        authored = function([{"Name": "Bonus", "Type": "float", "Default": "1.0"}, {"Name": "Zero", "Type": "float", "Default": "0.0"},
                             {"Name": "Bold", "Type": "bool", "Default": "true"}])
        extracted = function([{"Name": "Bonus", "Type": "float", "Default": "1.000000"}, {"Name": "Zero", "Type": "float"},
                              {"Name": "Bold", "Type": "bool", "Default": "True"}])
        self.assertEqual(section_mismatch_reasons("FunctionGraphs", authored, extracted, self_class=ACTOR_CLASS), {})
        extracted[0]["Signature"]["Inputs"][0]["Default"] = "2.0"
        reason = section_mismatch_reasons("FunctionGraphs", authored, extracted, self_class=ACTOR_CLASS)["Move"]
        self.assertIn("Bonus Default '1.0', read back '2.0'", reason)

    def test_function_input_defaults_and_return_values_are_extracted(self):
        # The editor keeps a function input's default and a return node's values as the pins' autogenerated
        # defaults (K2Node_FunctionEntry / K2Node_FunctionResult): they are extracted when not the type's zero.
        def edit(value):
            _node(value, ENTRY_GUID)["pins"][1].update(default_value="1.5", is_autogenerated_default=True)
            _node(value, RESULT_GUID)["pins"][1].update(default_value="0.25", is_autogenerated_default=True)
        body = _extract(_live(SIGNATURE, edit))
        function = next(graph for graph in body["FunctionGraphs"] if graph["Name"] == "AddHealth")
        self.assertEqual(function["Signature"]["Inputs"][0].get("Default"), "1.5")
        self.assertNotIn("Default", function["Signature"]["Outputs"][0])
        result = next(node for node in function["Nodes"] if node["Id"] == "Result")
        self.assertEqual(result["PinOverrides"], [{"Pin": "NewHealth", "DefaultValue": "0.25"}])

    def test_return_value_omitted_from_the_document_is_set_to_zero(self):
        def edit(value):
            _node(value, RESULT_GUID)["pins"][1].update(default_value="0.25", is_autogenerated_default=True)
        body = {"FunctionGraphs": [{"Name": "AddHealth", "Signature": {
            "Inputs": [{"Name": "Amount", "Type": "float"}], "Outputs": [{"Name": "NewHealth", "Type": "float"}]},
            "Nodes": [{"Id": "Result", "Implicit": "result"}], "Links": [{"From": "Entry:then", "To": "Result:execute"}]}]}
        briefs = _plan(body, SIGNATURE, edit).briefs()
        self.assertIn(("graph.pin.default.set", FUNC, {"pin": {"node": "Result", "pin": "NewHealth", "direction": "input"},
                                                       "kind": "value", "value": "0.0"}), briefs)
        body["FunctionGraphs"][0]["Nodes"][0]["PinOverrides"] = [{"Pin": "NewHealth", "DefaultValue": "0.25"}]
        self.assertEqual(_plan(body, SIGNATURE, edit).briefs(), [])

    def test_empty_real_pin_default_reads_as_zero(self):
        # A promotable operator's reconstructed pin keeps no text for a value equal to its default.
        def edit(value):
            node = _node(value, RESULT_GUID)
            node["pins"][1].update(default_value="", is_autogenerated_default=True)
        live = _live(SIGNATURE, edit)
        pin = next(node for graph in live.graphs for node in graph.nodes if node.guid == RESULT_GUID).pins[1]
        from asset_document.graphs.reconcile import same_pin_value
        self.assertTrue(same_pin_value(pin, "value", "0.0"))
        self.assertTrue(same_pin_value(pin, "value", "0"))
        self.assertFalse(same_pin_value(pin, "value", "0.5"))

    def test_links_of_a_removed_input_break_before_the_signature_change(self):
        # Deleting a function input and its link in one apply.
        def edit(value):
            entry, result = _node(value, ENTRY_GUID), _node(value, RESULT_GUID)
            entry["pins"][1]["linked_to"] = [{"node_guid": RESULT_GUID, "pin_name": "NewHealth"}]
            result["pins"][1]["linked_to"] = [{"node_guid": ENTRY_GUID, "pin_name": "Amount"}]
            _graph(value, "AddHealth")["links"].append({"from": {"node_guid": ENTRY_GUID, "pin_name": "Amount"},
                                                        "to": {"node_guid": RESULT_GUID, "pin_name": "NewHealth"}})
        body = {"FunctionGraphs": [{"Name": "AddHealth", "Signature": {
            "Inputs": [], "Outputs": [{"Name": "NewHealth", "Type": "float"}]},
            "Links": [{"From": "Entry:then", "To": "Result:execute"}]}]}
        ops = [op.op for op in _plan(body, SIGNATURE, edit).ops]
        self.assertEqual(ops[:2], ["graph.pin.break", "graph.node.user_pins.set"])
        self.assertEqual(ops.count("graph.pin.break"), 1)

    def test_reused_ghost_event_takes_its_ghost_parent_call_away(self):
        # A child Blueprint's ghost Tick comes with a ghost "Parent: Tick"; placing Tick from the palette
        # removes both (RemoveGhostNodes). Linking the ghost would make the parent call real.
        parent_guid = "B00000000000000000000000000000AA"

        def edit(value):
            graph = _graph(value, "EventGraph")
            tick = _node(value, TICK_GUID)
            next(pin for pin in tick["pins"] if pin["name"] == "then")["linked_to"] = [
                {"node_guid": parent_guid, "pin_name": "execute"}]
            call = deepcopy(tick)
            call.update(node_guid=parent_guid, **{"class": "/Script/BlueprintGraph.K2Node_CallParentFunction"},
                        action_key="K2:CallParentFunction:/Script/Engine.Actor:ReceiveTick", title="Parent: Tick",
                        position={"x": 300, "y": 416})
            call["pins"] = [_pin("execute", "input", "exec", linked=[(TICK_GUID, "then")]), _pin("then", "output", "exec")]
            graph["nodes"].append(call)
            graph["links"].append({"from": {"node_guid": TICK_GUID, "pin_name": "then"},
                                   "to": {"node_guid": parent_guid, "pin_name": "execute"}})
        body = {"UbergraphPages": [{"Name": "EventGraph", "Nodes": [
            {"Id": "Tick", "Action": "K2:Tick"}, {"Id": "Print", "Action": "K2:PrintString"}],
            "Links": [{"From": "Tick:then", "To": "Print:execute"}]}]}
        briefs = _plan(body, EMPTY, edit).briefs()
        self.assertEqual(briefs[0], ("graph.node.remove", "UbergraphPages/EventGraph",
                                     {"node_guid": parent_guid, "action_key": "K2:CallParentFunction:/Script/Engine.Actor:ReceiveTick"}))
        self.assertEqual(sum(1 for brief in briefs if brief[0] == "graph.node.remove"), 1)


class BlueprintMemberVerificationTests(unittest.TestCase):
    def test_components_are_matched_by_name_and_attach_to_takes_the_subobject_name(self):
        # Listed children first; AttachTo CollisionCylinder is the Character's CapsuleComponent.
        from asset_document.profiles import ublueprint_members as members
        # An owned component without AttachTo attaches to the native root (read back as CapsuleComponent).
        query = {"scene_root": "CapsuleComponent", "native_component_names": {"CollisionCylinder": "CapsuleComponent"},
                 "components": [
            {"name": "PP_Bullet", "scope": "owned", "class": "/Script/Engine.PostProcessComponent", "attach_to": "CapsuleComponent"},
            {"name": "CameraBoom", "scope": "owned", "class": "/Script/Engine.SpringArmComponent", "attach_to": "CapsuleComponent",
             "properties": {"TargetArmLength": 350.79998779296875}},
            {"name": "FollowCamera", "scope": "owned", "class": "/Script/Engine.CameraComponent", "attach_to": "CameraBoom"}]}
        extracted = members.members_from_query(query)
        authored = members.canonical_members({"Components": [
            {"Name": "FollowCamera", "Class": "/Script/Engine.CameraComponent", "AttachTo": "CameraBoom",
             "Properties": {"FieldOfView": 90.0}},
            {"Name": "CameraBoom", "Class": "/Script/Engine.SpringArmComponent", "AttachTo": "CollisionCylinder",
             "Properties": {"TargetArmLength": 350.8}},
            {"Name": "PP_Bullet", "Class": "/Script/Engine.PostProcessComponent"}]})
        aliases = {members.NATIVE_NAMES: members.native_component_names(query)}
        self.assertEqual(members.diff_members(authored, extracted, {}, {}, False, aliases), [])
        self.assertEqual(members.plan_component_attach(authored, query), [])
        authored["Components"][1]["Properties"]["TargetArmLength"] = 300.0
        differences = members.diff_members(authored, extracted, {}, {}, False, aliases)
        self.assertEqual([(d.path, d.before, d.after) for d in differences],
                         [("/Body/Components/1/Properties/TargetArmLength", 300.0, 350.79998779296875)])
        authored["Components"][2]["AttachTo"] = "CameraBoom"
        self.assertEqual([d.path for d in members.diff_members(authored, extracted, {}, {}, False, aliases)],
                         ["/Body/Components/1/Properties/TargetArmLength", "/Body/Components/2/AttachTo"])

    def test_an_omitted_attach_to_is_the_owned_scene_root(self):
        # An Actor Blueprint without a native root; the first scene component became the root and the second,
        # written without AttachTo, is attached to it (the Components panel's Add). The query names that root.
        from asset_document.profiles import ublueprint_members as members
        query = {"scene_root": "Trigger", "native_component_names": {}, "components": [
            {"name": "Trigger", "scope": "owned", "class": "/Script/Engine.BoxComponent", "attach_to": ""},
            {"name": "Sensor", "scope": "owned", "class": "/Script/Engine.SphereComponent", "attach_to": "Trigger"}]}
        extracted = members.members_from_query(query)
        authored = members.canonical_members({"Components": [
            {"Name": "Trigger", "Class": "/Script/Engine.BoxComponent"},
            {"Name": "Sensor", "Class": "/Script/Engine.SphereComponent"}]})
        names = {members.NATIVE_NAMES: members.native_component_names(query)}
        self.assertEqual(members.diff_members(authored, extracted, {}, {}, False, names), [])
        self.assertEqual(members.plan_component_attach(authored, query), [])
        # Without the owned root in the query, the omitted AttachTo reads as a difference (the mismatch).
        bare = {members.NATIVE_NAMES: members.native_component_names(dict(query, scene_root=""))}
        self.assertEqual([d.path for d in members.diff_members(authored, extracted, {}, {}, False, bare)],
                         ["/Body/Components/1/AttachTo"])

    def test_maps_compare_by_entries_in_text_and_json_forms(self):
        # A TMap inside an array of structs, written as UE text or as a JSON object.
        from asset_document.profiles.ublueprint_members import values_equal
        cube, sphere = "/Engine/BasicShapes/Cube.Cube", "/Engine/BasicShapes/Sphere.Sphere"
        observed = f"((/Script/Engine.StaticMesh'{cube}', /Script/Engine.StaticMesh'{sphere}'))"
        self.assertTrue(values_equal(f"(({cube}, {sphere}))", observed))
        self.assertTrue(values_equal({cube: "/Engine/BasicShapes/Sphere"}, observed))
        self.assertFalse(values_equal({cube: cube}, observed))
        self.assertTrue(values_equal([{"Weights": {"Light": 0.8}}], [{"Weights": '(("Light", 0.800000))'}]))
        self.assertTrue(values_equal("((Light, 0.25),(Heavy, 1.5))", '(("Heavy", 1.500000),("Light", 0.250000))'))
        self.assertFalse(values_equal("((Light, 0.25))", '(("Light", 0.500000))'))


class NiagaraVerificationTests(unittest.TestCase):
    def test_array_elements_list_the_members_they_set(self):
        # Meshes / OverrideMaterials elements and curve Keys with some fields.
        from asset_document.profiles.niagara_apply import property_changes
        live = {"Meshes": [{"Mesh": "/Engine/BasicShapes/Cube.Cube", "Scale": {"X": 1.0, "Y": 1.0, "Z": 1.0}, "LODBias": 0},
                           {"Mesh": "/Engine/BasicShapes/Sphere.Sphere", "Scale": {"X": 2.0, "Y": 2.0, "Z": 2.0}, "LODBias": 0}],
                "Curve": {"Keys": [{"Time": 0.0, "Value": 1.0, "InterpMode": "RCIM_Linear", "TangentMode": "RCTM_Auto"}],
                          "DefaultValue": 3.4028235e38}}
        defaults = {"Meshes": [], "Curve": {"Keys": [], "DefaultValue": 3.4028235e38}}
        authored = {"Meshes": [{"Mesh": "/Engine/BasicShapes/Cube.Cube"}, {"Mesh": "/Engine/BasicShapes/Sphere.Sphere",
                                                                          "Scale": {"X": 2.0, "Y": 2.0, "Z": 2.0}}],
                    "Curve": {"Keys": [{"Time": 0.0, "Value": 1.0}]}}
        self.assertEqual(property_changes(authored, live, defaults), ({}, []))
        authored["Meshes"][0]["LODBias"] = 1
        self.assertEqual(list(property_changes(authored, live, defaults)[0]), ["Meshes"])

    def test_module_input_curve_lists_some_key_fields(self):
        from asset_document.profiles.niagara_stack import _same_input
        have = {"DataInterface": {"Class": "/Script/Niagara.NiagaraDataInterfaceCurve", "Properties": {
            "Curve": {"Keys": [{"Time": 0.0, "Value": 1.0, "InterpMode": "RCIM_Cubic", "ArriveTangent": 0.0}],
                      "DefaultValue": 3.4028235e38, "PreInfinityExtrap": "RCCE_Constant"}}}}
        want = {"DataInterface": {"Class": "/Script/Niagara.NiagaraDataInterfaceCurve", "Properties": {
            "Curve": {"Keys": [{"Time": 0.0, "Value": 1.0, "InterpMode": "RCIM_Cubic"}]}}}}
        self.assertTrue(_same_input(want, have))
        want["DataInterface"]["Properties"]["Curve"]["Keys"][0]["Value"] = 0.5
        self.assertFalse(_same_input(want, have))


