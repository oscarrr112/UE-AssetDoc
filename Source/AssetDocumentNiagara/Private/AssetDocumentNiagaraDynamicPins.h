struct FDynamicPinsAccess : public UNiagaraNodeWithDynamicPins
{
	using UNiagaraNodeWithDynamicPins::AllowDynamicPins;
	using UNiagaraNodeWithDynamicPins::CanModifyPin;
	using UNiagaraNodeWithDynamicPins::CanRemovePin;
	using UNiagaraNodeWithDynamicPins::CanMovePin;
	using UNiagaraNodeWithDynamicPins::RemoveDynamicPin;
	using UNiagaraNodeWithDynamicPins::MoveDynamicPin;
	using UNiagaraNodeWithDynamicPins::OnNewTypedPinAdded;

	static bool CallAllowDynamicPins(const UNiagaraNodeWithDynamicPins& Node)
	{
		bool (UNiagaraNodeWithDynamicPins::*Fn)() const = &FDynamicPinsAccess::AllowDynamicPins;
		return (Node.*Fn)();
	}
	static bool CallCanModifyPin(const UNiagaraNodeWithDynamicPins& Node, const UEdGraphPin* Pin)
	{
		bool (UNiagaraNodeWithDynamicPins::*Fn)(const UEdGraphPin*) const = &FDynamicPinsAccess::CanModifyPin;
		return (Node.*Fn)(Pin);
	}
	static bool CallCanRemovePin(const UNiagaraNodeWithDynamicPins& Node, const UEdGraphPin* Pin)
	{
		bool (UNiagaraNodeWithDynamicPins::*Fn)(const UEdGraphPin*) const = &FDynamicPinsAccess::CanRemovePin;
		return (Node.*Fn)(Pin);
	}
	static bool CallCanMovePin(const UNiagaraNodeWithDynamicPins& Node, const UEdGraphPin* Pin, int32 Direction)
	{
		bool (UNiagaraNodeWithDynamicPins::*Fn)(const UEdGraphPin*, int32) const = &FDynamicPinsAccess::CanMovePin;
		return (Node.*Fn)(Pin, Direction);
	}
	static void CallRemoveDynamicPin(UNiagaraNodeWithDynamicPins& Node, UEdGraphPin* Pin)
	{
		void (UNiagaraNodeWithDynamicPins::*Fn)(UEdGraphPin*) = &FDynamicPinsAccess::RemoveDynamicPin;
		(Node.*Fn)(Pin);
	}
	static void CallMoveDynamicPin(UNiagaraNodeWithDynamicPins& Node, UEdGraphPin* Pin, int32 Amount)
	{
		void (UNiagaraNodeWithDynamicPins::*Fn)(UEdGraphPin*, int32) = &FDynamicPinsAccess::MoveDynamicPin;
		(Node.*Fn)(Pin, Amount);
	}
	static void CallOnNewTypedPinAdded(UNiagaraNodeWithDynamicPins& Node, UEdGraphPin*& Pin)
	{
		void (UNiagaraNodeWithDynamicPins::*Fn)(UEdGraphPin*&) = &FDynamicPinsAccess::OnNewTypedPinAdded;
		(Node.*Fn)(Pin);
	}
};

// Map Get default value pins (UNiagaraNodeParameterMapGet::GetDefaultPin / GetOutputPinForDefault, not exported):
// each output pin has an unnamed input pin holding the value used when nothing set the parameter before. The pair
// is the node's PinOutputToPinDefaultPersistentId (output persistent guid -> default pin persistent guid), read
// through reflection. Documents name a default pin after its output pin (direction input).
inline bool IsMapGet(const UEdGraphNode& Node)
{
	return Node.GetClass()->GetFName() == TEXT("NiagaraNodeParameterMapGet");
}

inline const FGuid* MapGetDefaultPinGuid(const UEdGraphNode& Node, const FGuid& OutputGuid)
{
	const FMapProperty* Property = IsMapGet(Node) ? FindFProperty<FMapProperty>(Node.GetClass(), TEXT("PinOutputToPinDefaultPersistentId")) : nullptr;
	if (Property == nullptr || !Property->KeyProp->IsA<FStructProperty>())
	{
		return nullptr;
	}
	FScriptMapHelper Map(Property, Property->ContainerPtrToValuePtr<void>(&Node));
	return reinterpret_cast<const FGuid*>(Map.FindValueFromHash(&OutputGuid));
}

inline UEdGraphPin* MapGetDefaultPin(const UEdGraphNode& Node, const UEdGraphPin& OutputPin)
{
	const FGuid* DefaultGuid = OutputPin.Direction == EGPD_Output ? MapGetDefaultPinGuid(Node, OutputPin.PersistentGuid) : nullptr;
	if (DefaultGuid == nullptr)
	{
		return nullptr;
	}
	for (UEdGraphPin* Pin : Node.Pins)
	{
		if (Pin != nullptr && Pin->Direction == EGPD_Input && Pin->PersistentGuid == *DefaultGuid)
		{
			return Pin;
		}
	}
	return nullptr;
}

inline const UEdGraphPin* MapGetOutputForDefault(const UEdGraphNode& Node, const UEdGraphPin& DefaultPin)
{
	if (DefaultPin.Direction != EGPD_Input || !IsMapGet(Node))
	{
		return nullptr;
	}
	for (const UEdGraphPin* Pin : Node.Pins)
	{
		if (Pin != nullptr && Pin->Direction == EGPD_Output && MapGetDefaultPin(Node, *Pin) == &DefaultPin)
		{
			return Pin;
		}
	}
	return nullptr;
}
// The default a new pin of this type gets. Pins saved by older versions may have no autogenerated default; they hold
// the type's default (UNiagaraNode::SetPinDefaultToTypeDefaultIfUnset), which is then not an authored value.
inline FString GeneratedPinDefault(const UEdGraphPin& Pin)
{
	if (!Pin.AutogeneratedDefaultValue.IsEmpty())
	{
		return Pin.AutogeneratedDefaultValue;
	}
	const UEdGraphSchema_Niagara* Schema = GetDefault<UEdGraphSchema_Niagara>();
	const FNiagaraTypeDefinition Type = Schema->PinToTypeDefinition(&Pin);
	if (!Type.IsValid() || Type.IsDataInterface() || Type.IsUObject() || Type.GetScriptStruct() == nullptr)
	{
		return FString();
	}
	FNiagaraVariable Variable(Type, Pin.PinName);
	FNiagaraEditorUtilities::ResetVariableToDefaultValue(Variable);
	FString Default;
	return Schema->TryGetPinDefaultValueFromNiagaraVariable(Variable, Default) ? Default : FString();
}
