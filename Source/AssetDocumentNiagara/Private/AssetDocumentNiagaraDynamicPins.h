// The pin menu of Niagara nodes with user-added pins (UNiagaraNodeWithDynamicPins: Map Get / Set, custom HLSL,
// variadic ops). The class is not exported and its pin edits are protected virtuals the node's own context menu
// and drop handlers call; this accessor names them so the graph adapter calls the same overrides (a custom HLSL
// node rebuilds its signature, a Map Get removes the matching default pin) through the virtual table.

